let fallbackLanguage: Lang = "fr";
export function getUiLanguage(): Lang {
  try {
    const saved = typeof localStorage === "undefined" ? null : localStorage.getItem("edupay_lang");
    return saved === "fr" || saved === "en" ? saved : fallbackLanguage;
  } catch { return fallbackLanguage; }
}
export function persistUiLanguage(lang: Lang) {
  fallbackLanguage = lang;
  try { if (typeof localStorage !== "undefined") localStorage.setItem("edupay_lang", lang); } catch { /* Language still changes when storage is unavailable. */ }
  if (typeof document !== "undefined") document.documentElement.lang = lang;
}
const key = (value: string) => value.normalize("NFKC").trim().replace(/\s+/g, " ").toLocaleLowerCase();
const lookup = new Map<string, Copy>();
for (const [source, copy] of Object.entries(uiCopy)) {
  lookup.set(key(source), copy);
  lookup.set(key(copy.fr), copy);
  lookup.set(key(copy.en), copy);
}
/** Only known interface copy is translated; unknown values and user content are preserved. */
export function uiText(source: string | null | undefined, lang: Lang = getUiLanguage()): string {
  if (!source) return source ?? "";
  const copy = lookup.get(key(source));
  if (!copy) return source;
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return leading + copy[lang] + trailing;
}
