    next[index] = {
      ...next[index],
      ...Object.fromEntries(Object.entries(suggestion).filter(([key]) => key === "day" || !next[index].lockedFields?.[key as WeeklyEditableKey]))
    } as WeeklyPlanDay;
    form.setValue("weeklyPlan", next, { shouldDirty: true, shouldValidate: false });
