/** UI wording only: never translate names, authored content, stored status or permission values. */
export function adminDashboardText(value: unknown, language: 'fr'|'en'): string {
 const text=String(value??'')
 if(language==='fr'){
  const fixed=french[text];if(fixed)return fixed
  const rules:Array<[RegExp,string]>=[
   [/^(\d+) assigned course\(s\)$/,'$1 cours attribué(s)'],
   [/^(\d+) family file\(s\)$/,'$1 dossier(s) familial(aux)'],
   [/^(\d+) open report\(s\)$/,'$1 signalement(s) en cours'],
   [/^(\d+) student\(s\) are below the GPA or attendance threshold\.$/,'$1 élève(s) sont sous le seuil de moyenne ou de présence.'],
   [/^(\d+) incident report\(s\) require administrative follow-up\.$/,'$1 signalement(s) nécessitent un suivi administratif.'],
   [/^Application (.+) was rejected and saved in the central registry\.$/,'La candidature $1 a été refusée et enregistrée dans le registre central.'],
   [/^Academic document generated for (.+)\.$/,'Document scolaire généré pour $1.'],
   [/^(.+)'s academic document was approved for publication\.$/,'Le document scolaire de $1 a été approuvé pour publication.'],
   [/^(.+): paid (.+), outstanding (.+)\.$/,'$1 : réglé $2, solde dû $3.'],
  ];for(const[pattern,replacement]of rules)if(pattern.test(text))return text.replace(pattern,replacement)
 }else{
  const canonical=reverse.get(text)??text
  if(english[canonical])return english[canonical]
  if(reverse.has(text))return canonical
 }
 return text
}
export function adminDashboardMonth(value:string, language:'fr'|'en') {
 const index=['jan','feb','mar','apr','may','jun','jul','aug','sep','oct','nov','dec'].indexOf(String(value).toLowerCase().slice(0,3))
 return index<0?value:new Date(Date.UTC(2026,index,1)).toLocaleDateString(language==='fr'?'fr-CD':'en-US',{month:'short',timeZone:'UTC'})
}
